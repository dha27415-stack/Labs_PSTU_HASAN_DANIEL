#include <iostream>
using namespace std;

int main() {
    const int N_max = 100; // Максимальный размер массива
    int a[N_max];          // Объявление массива с максимальным размером
    int n;                 // Фактический размер массива

    // 1. Ввод фактического размера
    cout << "Введите фактический размер массива (макс. 100): ";
    cin >> n;

    // 2. Ввод элементов массива
    cout << "Введите " << n << " элементов:\n";
    for (int i = 0; i < n; i++) {
        cin >> a[i];
    }

    // 3. Ввод начального индекса K
    int K;
    cout << "Введите начальный индекс K (от 0 до " << n - 1 << "): ";
    cin >> K;

    // 4. Печать по кольцу влево
    cout << "\nПечать по кольцу влево, начиная с индекса " << K << ":\n";
    for (int i = 0; i < n; i++) {
        int current_index = (K - i + n) % n;
        cout << "a[" << current_index << "] = " << a[current_index] << endl;
    }

    // 5. Поиск максимального значения
    int max_val = a[0];
    for (int i = 1; i < n; i++) {
        if (a[i] > max_val) {
            max_val = a[i];
        }
    }
    cout << "\nМаксимальное значение: " << max_val << endl;

    // 6. Удаление элементов, совпадающих с максимальным значением, и сдвиг
    for (int i = 0; i < n; i++) {
        if (a[i] == max_val) {
            for (int j = i; j < n - 1; j++) {
                a[j] = a[j + 1];
            }
            n--; // Уменьшение фактического размера
            i--; // Повторная проверка текущего индекса
        }
    }

    cout << "Размер массива после удаления максимальных элементов: " << n << endl;

    // 7. Печать по кольцу вправо после удаления
    if (n > 0) {
        K = K % n;
    }

    cout << "\nПечать по кольцу вправо, начиная с индекса " << K << ":\n";
    for (int i = 0; i < n; i++) {
        int current_index = (K + i) % n;
        cout << "a[" << current_index << "] = " << a[current_index] << endl;
    }

    return 0;
}