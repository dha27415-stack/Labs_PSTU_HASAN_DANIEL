#define _CRT_SECURE_NO_WARNINGS
#include <iostream>
#include <cmath>
#include <clocale>
#include <windows.h>
#include <iomanip>

using namespace std;
 
int main() {
    // Настройка кодировки консоли для поддержки кириллицы в комментариях
    // إعداد ترميز وحدة التحكم لدعم اللغة الروسية في التعليقات
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    // Вывод заголовка программы на английском во избежание проблем с кодировкой
    // طباعة عنوان البرنامج بالإنجليزية لتجنب مشاكل الترميز
    cout << "=== Laboratory Work 3. Variant 23 ===" << endl;

    // Инициализация границ диапазона и шага для варианта 23 (от 0.1 до 1.0)
    // تهيئة حدود النطاق والخطوة للبديل 23 (من 0.1 إلى 1.0)
    double a = 0.1;
    double b = 1.0;
    int k = 10;
    double h = (b - a) / k; // Шаг изменения аргумента x / خطوة تغير الوسيط x

    // Заданное количество членов для пункта а) и заданная точность для пункта б)
    // عدد الحدود المحدد للفقرة (أ) والدقة المحددة للفقرة (ب)
    int n_given = 15;       // n = 15 للبديل 23
    double eps = 0.0001;    // الدقة المطلوب الوصول إليها

    // Установка формата вывода чисел с плавающей точкой
    // ضبط تنسيق إخراج الأرقام العشرية بدقة مرتبة
    cout << fixed << setprecision(6);
    cout << "-----------------------------------------------------------------" << endl;
    cout << " x\t\t Exact y\t Sum (n=15)\t Sum (eps)" << endl;
    cout << "-----------------------------------------------------------------" << endl;

    // Цикл для вычисления значений в диапазоне от a до b с шагом h
    // حلقة تكرار لحساب القيم في النطاق من a إلى b بالخطوة h
    for (double x = a; x <= b + 1e-9; x += h) {
        // Вычисление точного значения функции для варианта 23: y = 2 * (cos^2(x) - 1)
        // حساب القيمة الدقيقة للدالة للبديل 23: y = 2 * (cos^2(x) - 1)
        double exact_y = 2 * (pow(cos(x), 2) - 1);

        // а) Вычисление суммы для заданного n = 15
        // أ) حساب المجموع لعدد محدد n = 15
        double sum_n = 0.0;
        double term = -pow(2 * x, 2) / 2.0; // Первый член при n = 1 / الحد الأول عند n = 1
        sum_n += term;

        for (int n = 2; n <= n_given; n++) {
            // Рекуррентная формула для вычисления следующего члена ряда
            // صيغة تكرارية لحساب الحد التالي في المتسلسلة
            term = term * (-1.0) * pow(2 * x, 2) / ((2 * n - 1) * (2 * n));
            sum_n += term;
        }

        // б) Вычисление суммы с заданной точностью eps = 0.0001
        // ب) حساب المجموع بدقة محددة eps = 0.0001
        double sum_eps = 0.0;
        double term_eps = -pow(2 * x, 2) / 2.0;
        sum_eps += term_eps;
        int n_term = 2;

        // Цикл с условием точности для вычисления суммы
        // حلقة تكرار بشرط الدقة لحساب المجموع
        while (abs(term_eps) > eps) {
            term_eps = term_eps * (-1.0) * pow(2 * x, 2) / ((2 * n_term - 1) * (2 * n_term));
            sum_eps += term_eps;
            n_term++;

            // Предохранитель от бесконечного цикла
            // صمام حماية ضد الحلقة اللانهائية
            if (n_term > 1000) break;
        }

        // Вывод результатов строки таблицы в консоль
        // طباعة نتائج سطر الجدول في الكونسول
        cout << " " << x << "\t " << exact_y << "\t " << sum_n << "\t " << sum_eps << endl;
    }

    cout << "-----------------------------------------------------------------" << endl;

    return 0;
}
